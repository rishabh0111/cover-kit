// Lint the cover calendar: which style each post uses, in date order, and
// whether the rotation rules hold. A post is any folder named
// YYYY-MM-DD-<slug> holding a cover.json, at any depth under the root.
//   node check-rotation.js [root]           what the cover.json files say (root: $COVERS_DIR, else ./covers)
//   node check-rotation.js --plan           overlay <root>/rotation.json (styles planned for covers not yet redrawn)
//   node check-rotation.js --plan FILE      ...or a rotation file elsewhere
//   node check-rotation.js --from 2026-10-01   only enforce from this date (default: today)
//   node check-rotation.js --feed           also write styles/feed.js for the gallery's feed section
// Exit 1 if any enforced post breaks a hard rule.
const fs = require("fs");
const path = require("path");
const palette = require("./palette");

const TONE = { flow: "light", terminal: "dark", diff: "light", bignumber: "colour", chart: "light", versus: "split",
               sketch: "light", poster: "colour", sequence: "dark", anatomy: "light",
               list: "colour", timeline: "dark", compare: "colour" };
const args = process.argv.slice(2);
const flag = (name, withValue) => {
  const i = args.indexOf(name); if (i < 0) return undefined;
  const v = withValue && args[i + 1] && !args[i + 1].startsWith("--") ? args[i + 1] : true;
  args.splice(i, v === true ? 1 : 2); return v;
};
const from = (() => { const v = flag("--from", true); return typeof v === "string" ? v : new Date().toISOString().slice(0, 10); })();
const planArg = flag("--plan", true), writeFeed = flag("--feed");
const root = path.resolve(args[0] || process.env.COVERS_DIR || "covers");
if (!fs.existsSync(root)) { console.error(`no covers folder: ${root}`); process.exit(2); }
const planFile = typeof planArg === "string" ? path.resolve(planArg) : path.join(root, "rotation.json");
const plan = planArg ? (fs.existsSync(planFile) ? JSON.parse(fs.readFileSync(planFile, "utf8")) : (console.error(`no rotation file: ${planFile}`), process.exit(2))) : {};

const posts = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory() || e.name === "node_modules" || e.name.startsWith(".")) continue;
    const full = path.join(dir, e.name), m = e.name.match(/^(\d{4}-\d{2}-\d{2})-(.+)$/);
    const spec = path.join(full, "cover.json");
    if (m && fs.existsSync(spec)) {
      const s = palette.apply(JSON.parse(fs.readFileSync(spec, "utf8")), spec).spec;
      const current = s.style || (s.template === "bbg.html" ? "flow" : s.template || "?");
      const style = plan[m[2]] ? plan[m[2]].style : current;
      /* a ground set in the spec or palette changes the tone; a planned restyle uses that style's default */
      const tone = (style === current && palette.toneOf(s.ground)) || TONE[style] || "?";
      posts.push({ date: m[1], slug: m[2], dir: full, current, style, tone });
    } else walk(full);
  }
})(root);
posts.sort((a, b) => a.date.localeCompare(b.date));

/* rules
   HARD  same style as either of the two posts before it
   SOFT  same ground tone as the post before it (split never clashes)
   SOFT  flow more than once in any four consecutive posts                 */
let hard = 0;
posts.forEach((p, i) => {
  const flags = [];
  const prev = posts.slice(Math.max(0, i - 2), i);
  if (prev.some(q => q.style === p.style)) flags.push("HARD repeat within 3");
  const b = posts[i - 1];
  if (b && p.tone !== "split" && b.tone !== "split" && b.tone === p.tone) flags.push("soft same tone as previous");
  if (p.style === "flow" && posts.slice(Math.max(0, i - 3), i).some(q => q.style === "flow")) flags.push("soft flow twice in 4");
  const enforced = p.date >= from;
  if (enforced && flags.some(f => f.startsWith("HARD"))) hard++;
  console.log(`${p.date}  ${p.style.padEnd(10)} ${p.tone.padEnd(7)} ${p.slug.padEnd(38)} ${enforced ? "" : "(history) "}${flags.join(", ")}`);
});
const used = {}; posts.filter(p => p.date >= from).forEach(p => used[p.style] = (used[p.style] || 0) + 1);
console.log(`\nfrom ${from}: ` + Object.entries(used).map(([k, v]) => `${k} ${v}`).join(" · "));
console.log(hard ? `\n${hard} hard rule break(s)` : "\nrotation OK");
if (writeFeed) {
  /* gif paths are relative to styles/, where gallery.html reads them */
  const styles = path.join(__dirname, "styles");
  const feed = posts.filter(p => p.date >= from).map(({ date, slug, dir, current, style }) =>
    ({ date, slug, current, style, gif: path.relative(styles, path.join(dir, "cover.gif")).split(path.sep).join("/") }));
  fs.writeFileSync(path.join(styles, "feed.js"),
    "// generated by check-rotation.js --feed; do not edit\nwindow.FEED = " + JSON.stringify(feed, null, 1) + ";\n");
  console.log(`wrote styles/feed.js (${feed.length} posts)`);
}
process.exit(hard ? 1 : 0);
